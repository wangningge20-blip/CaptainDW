# Generate README.md from cards/data/beasts.json.
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DATA = os.path.join(ROOT, "cards", "data", "beasts.json")
ORDER = ["baize", "qilin", "fenghuang", "xuanwu", "zhuque", "chongming", "baihu", "chenghuang", "qinglong", "pixiu", "jiuweihu"]

data = json.load(open(DATA, encoding="utf-8"))
lines = []
lines.append("# 山海异兽录 · 十一神兽卡牌")
lines.append("")
lines.append("白泽、麒麟、凤凰、玄武、朱雀、重明鸟、白虎、乘黄、青龙、貔貅、九尾狐，共十一张正反双面的神兽卡牌。正面为神兽姿态与所居山水，背面为分类、神兽特点、功用技能与原型推测。每张卡牌都提供单面 PNG 与包含正反两面的合成渲染图。")
lines.append("")
lines.append("![白泽双面卡牌](cards/renders/baize-card.png)")
lines.append("")
lines.append("![凤凰双面卡牌](cards/renders/fenghuang-card.png)")
lines.append("")
lines.append("全部卡牌可在 [`cards/index.html`](cards/index.html) 中浏览。")
lines.append("")
lines.append("## 卡牌一览")
lines.append("")
lines.append("| No. | 神兽 | 卷部 | 正面场景 | 单面尺寸 | 双面合成 |")
lines.append("| --- | --- | --- | --- | --- | --- |")
for bid in ORDER:
    b = data[bid]
    lines.append("| %s | %s | %s | %s | 1500 × 2100 px | 3520 × 2520 px |" % (b["no"], b["name"], b["volume"], b["scene"]))
lines.append("")
lines.append("## 卡牌内容")
lines.append("")
for bid in ORDER:
    b = data[bid]
    lines.append("### %s · %s" % (b["name"], b["scene"]))
    lines.append("")
    lines.append("- **分类**：%s" % b["classification"])
    lines.append("- **神兽特点**：%s" % b["traits"])
    lines.append("- **功用技能**：%s" % b["powers"])
    lines.append("- **原型推测**：%s" % b["origin"])
    lines.append("- **引文**：%s——%s" % (b["quote"], b["quoteSource"]))
    lines.append("")
lines.append("## 文件结构")
lines.append("")
lines.append("```")
lines.append("cards/")
lines.append("  index.html            卡牌画廊（本地打开即可浏览）")
lines.append("  data/beasts.json      十一张卡牌的内容与视觉配置")
lines.append("  baize-front.html      白泽正面（750 × 1050 设计稿）")
lines.append("  baize-back.html       白泽背面")
lines.append("  ...                   其余十张同构")
lines.append("  present-<id>.html     各神兽正反双面展示页（3520 × 2520 渲染源）")
lines.append("  card.css              卡面样式")
lines.append("  grain.svg             纸纹")
lines.append("  assets/               背景、神兽线描、遮罩资源")
lines.append("  renders/              最终渲染 PNG")
lines.append("tools/")
lines.append("  build_cards.py        由数据生成九张新卡面与画廊")
lines.append("  render.ps1            用无头 Edge / Chrome 重新渲染全部 PNG")
lines.append("docs/evidence/          Before / After 视觉证据")
lines.append("ATTRIBUTION.md          图像来源与公有领域说明")
lines.append("```")
lines.append("")
lines.append("## 重新渲染")
lines.append("")
lines.append("需要 Windows 上的 Microsoft Edge 或 Google Chrome：")
lines.append("")
lines.append("```powershell")
lines.append("powershell -ExecutionPolicy Bypass -File tools/render.ps1")
lines.append("```")
lines.append("")
lines.append("只渲染某几张时使用 `-Only`：")
lines.append("")
lines.append("```powershell")
lines.append("powershell -ExecutionPolicy Bypass -File tools/render.ps1 -Only fenghuang-front,xuanwu-card")
lines.append("```")
lines.append("")
lines.append("`render.ps1` 输出：")
lines.append("")
lines.append("- `cards/renders/<id>-front.png`、`<id>-back.png`（各 1500 × 2100）")
lines.append("- `cards/renders/<id>-card.png`（各 3520 × 2520，正反两面）")
lines.append("")
lines.append("## 图像来源")
lines.append("")
lines.append("神兽线描取自《古今图书集成 · 禽虫典》中的白泽、麒麟、凤凰、鸾鸟、鵔鸟、虎、貔、九尾狐、乘黄、龙、龟、青蛇诸图（公有领域，Wikimedia Commons），经重新设色与局部遮罩；山水背景取自《雪景寒林图》、王希孟《千里江山图》、郭熙《早春图》、范宽《溪山行旅图》局部（均为公有领域），经裁切与调色。完整来源与链接见 [ATTRIBUTION.md](ATTRIBUTION.md)。")
lines.append("")
lines.append("朱雀、重明鸟、白虎、青龙、貔貅分别以同书中的鸾鸟、鵔鸟、虎、龙、貔图作为形象参照；玄武由龟图与青蛇图合绘。卡面为艺术再设计，不声称与古籍原图逐一对应。")
lines.append("")
lines.append("卡面排版、构图、配色与文案为本仓库新增内容。")
lines.append("")
lines.append("## 说明")
lines.append("")
lines.append("- 卡面以 CSS 尺寸 750 × 1050（5:7）设计，2 倍缩放输出 1500 × 2100 PNG。")
lines.append("- 正反合成图包含两面的完整图像、卡牌投影与编号标签。")
lines.append("- 文字内容参考《山海经》《云笈七签》《说文解字》《礼记》《淮南子》《拾遗记》等传世文献；「原型推测」为编者按，不作学术定论。")
lines.append("- 仓库中的 `renders/` 为便于审阅的压缩 PNG；重新运行 `render.ps1` 可得到未压缩版本。")
lines.append("")
open(os.path.join(ROOT, "README.md"), "w", encoding="utf-8").write("\n".join(lines))
print("README written", len(lines), "lines")
